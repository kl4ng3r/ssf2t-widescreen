# Generates font.h: an 8-bit alpha atlas of printable ASCII from DejaVu Sans Bold
# (Bitstream Vera / DejaVu license, see README) for the launcher's on-screen text.
import sys
from PIL import Image, ImageDraw, ImageFont
TTF = sys.argv[1]; OUT = sys.argv[2]; PX = 40
f = ImageFont.truetype(TTF, PX)
asc, desc = f.getmetrics(); CH = asc + desc + 2; CW = PX
cols = 16; rows = 6
im = Image.new('L', (cols * CW, rows * CH), 0); d = ImageDraw.Draw(im)
adv = []
for i in range(95):
    c = chr(32 + i); x = (i % cols) * CW; y = (i // cols) * CH
    d.text((x + 2, y + 1), c, font=f, fill=255)
    adv.append(int(round(f.getlength(c))) + 1)
data = im.tobytes()
with open(OUT, 'w') as o:
    o.write('// Generated by tools/gen_font.py from DejaVu Sans Bold (Bitstream Vera / DejaVu fonts license).\n')
    o.write(f'#define FONT_W {im.width}\n#define FONT_H {im.height}\n#define FONT_CW {CW}\n#define FONT_CH {CH}\n#define FONT_COLS {cols}\n')
    o.write('static const unsigned char font_adv[95] = {' + ','.join(map(str, adv)) + '};\n')
    o.write('static const unsigned char font_px[] = {\n')
    for k in range(0, len(data), 40):
        o.write(','.join(str(b) for b in data[k:k + 40]) + ',\n')
    o.write('};\n')
print(im.size, len(data))
